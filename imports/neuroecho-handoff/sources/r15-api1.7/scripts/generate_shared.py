#!/usr/bin/env python3
"""Generate the versioned design/copy resources used by each client."""
from pathlib import Path
import argparse, json, re
ROOT=Path(__file__).resolve().parents[1]
def identifier(value):
    return re.sub(r'[^A-Za-z0-9_]', '_', value)
def literal(value, kotlin=False):
    text=json.dumps(value, ensure_ascii=False)
    return text.replace('$', '\\$') if kotlin else text

def outputs():
    design=json.loads((ROOT/'shared/design/tokens.json').read_text(encoding='utf-8'))
    copy=json.loads((ROOT/'shared/product/copy.zh-CN.json').read_text(encoding='utf-8'))['strings']
    colors=design['colors'];dimensions=design['dimensions'];defaults=design.get('defaults',{})
    header='Generated from shared specs. Do not edit this file by hand.'
    css='/* '+header+' */\n:root {\n'+''.join(f'  --{key}: {value};\n' for key,value in colors.items())+'}\n'
    data={'colors':colors,'copy':copy,'dimensions':dimensions,'defaults':defaults}
    js='// '+header+'\nexport const EchoColors = Object.freeze('+json.dumps(colors,ensure_ascii=False,indent=2)+');\nexport const EchoCopy = Object.freeze('+json.dumps(copy,ensure_ascii=False,indent=2)+');\nexport const EchoDefaults = Object.freeze('+json.dumps(defaults,ensure_ascii=False,indent=2)+');\n'
    browser='// '+header+'\nwindow.EchoShared = Object.freeze('+json.dumps(data,ensure_ascii=False,indent=2)+');\n'
    swift='// '+header+'\npublic enum EchoSharedReference {\n'
    swift+=''.join(f'    public static let color_{identifier(key)} = {literal(value)}\n' for key,value in colors.items())
    swift+=''.join(f'    public static let copy_{identifier(key)} = {literal(value)}\n' for key,value in copy.items())
    swift+=''.join(f'    public static let dimension_{identifier(key)} = {value}\n' for key,value in dimensions.items())
    swift+=''.join(f'    public static let default{key[0].upper()+key[1:]} = {str(value).lower()}\n' for key,value in defaults.items() if not key.startswith(('min','max')))
    swift+=''.join(f'    public static let {key} = {value}\n' for key,value in defaults.items() if key.startswith(('min','max')))+'}\n'
    kotlin='// '+header+'\npackage cn.xinji.echo.shared\n\nobject EchoSharedReference {\n'
    kotlin+=''.join(f'    const val COLOR_{identifier(key).upper()} = {literal(value,True)}\n' for key,value in colors.items())
    kotlin+=''.join(f'    const val COPY_{identifier(key).upper()} = {literal(value,True)}\n' for key,value in copy.items())
    kotlin+=''.join(f'    const val DIMENSION_{identifier(key).upper()} = {value}\n' for key,value in dimensions.items())
    for key,value in defaults.items():
        label=re.sub(r'(?<!^)(?=[A-Z])','_',key).upper()
        if not key.startswith(('min','max')):label='DEFAULT_'+label
        literal_value=str(value).lower()+('f' if isinstance(value,float) else '')
        kotlin+=f'    const val {label} = {literal_value}\n'
    kotlin+='}\n'
    return {'design.css':css,'ui.mjs':js,'runtime.js':browser,'EchoSharedReference.swift':swift,'EchoSharedReference.kt':kotlin}

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');args=p.parse_args()
    directory=ROOT/'shared/generated'
    for name,content in outputs().items():
        target=directory/name
        if args.check:
            if not target.exists() or target.read_text()!=content:raise SystemExit('Generated reference drift: '+name+'; run scripts/generate_shared.py after review.')
        else:
            directory.mkdir(parents=True,exist_ok=True);target.write_text(content, encoding='utf-8')
    print('Shared generated resources match.' if args.check else 'Generated CSS, JS, Swift and Kotlin resources.')
if __name__=='__main__':main()
